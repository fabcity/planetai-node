"""The Fab City Index places a node can belong to, and which one is nearest.

Stdlib only: the node's Python has no PyYAML, and `planetai place` calls this file's command line instead of
redoing the sums in bash.

  python3 packs/index/place.py --nearest <lat> <lon>   one JSON line: the nearest place, or null
  python3 packs/index/place.py --known <slug>          exit 0 if the Index tracks it, 2 if not

places.json is generated by tools/build_index_places.py. Its centres are approximate and assert no border, so
"nearest" is a suggestion for the household to confirm, never a membership.
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load():
    with open(os.path.join(HERE, "places.json")) as f:
        return json.load(f)["places"]


def _km(lat1, lon1, lat2, lon2):
    """Great-circle distance (haversine). The sin() of half the longitude difference wraps at the antimeridian."""
    p1, p2 = math.radians(lat1), math.radians(lat2)
    a = math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(math.radians(lon2 - lon1) / 2) ** 2
    return 6371.0 * 2 * math.asin(math.sqrt(a))


def nearest(lat, lon, places, max_km=150):
    """The closest place with a centre, if one is within max_km; otherwise None. Beyond that a suggestion is a
    guess: a node in Menorca is 240 km from Barcelona and is not in it."""
    best, best_km = None, max_km
    for p in places:
        if p["lat"] is None:
            continue
        d = _km(lat, lon, p["lat"], p["lon"])
        if d <= best_km:
            best, best_km = p, d
    return best


def known(slug, places):
    return any(p["slug"] == slug for p in places)


if __name__ == "__main__":
    a = sys.argv[1:]
    if len(a) == 3 and a[0] == "--nearest":
        print(json.dumps(nearest(float(a[1]), float(a[2]), load()), ensure_ascii=False))
    elif len(a) == 2 and a[0] == "--known":
        sys.exit(0 if known(a[1], load()) else 2)
    else:
        sys.exit("usage: place.py --nearest <lat> <lon> | --known <slug>")
